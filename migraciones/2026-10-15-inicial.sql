-- Kitsune Stats: base inicial (base de datos kitsune_stats).

-- Líderes de One Piece Card Game: el "deck" de cada partida.
CREATE TABLE lideres (
    codigo     VARCHAR(20)  PRIMARY KEY,
    nombre     VARCHAR(120) NOT NULL,
    colores    TEXT[]       NOT NULL CHECK (cardinality(colores) BETWEEN 1 AND 2),
    set_codigo VARCHAR(10)  NOT NULL,
    imagen_url VARCHAR(500),
    activo     BOOLEAN      NOT NULL DEFAULT true,
    creado_en  TIMESTAMP    NOT NULL DEFAULT now()
);

-- Una partida desde el lado de quien la registró. Con rival (cuenta Kitsune) el rival la
-- confirma o la rechaza; confirmada cuenta para los dos y, en las globales, una vez.
CREATE TABLE partidas (
    id               BIGSERIAL    PRIMARY KEY,
    jugador_id       BIGINT       NOT NULL,
    jugador_username VARCHAR(60)  NOT NULL,
    lider            VARCHAR(20)  NOT NULL REFERENCES lideres (codigo),
    rival_lider      VARCHAR(20)  NOT NULL REFERENCES lideres (codigo),
    empece           BOOLEAN      NOT NULL,
    gane             BOOLEAN      NOT NULL,
    jugada_en        DATE         NOT NULL,
    tipo             VARCHAR(10)  NOT NULL CHECK (tipo IN ('CASUAL', 'TORNEO')),
    rival_id         BIGINT,
    rival_username   VARCHAR(60),
    confirmacion     VARCHAR(12)  NOT NULL DEFAULT 'SIN_RIVAL' CHECK (confirmacion IN ('SIN_RIVAL', 'PENDIENTE', 'CONFIRMADA', 'RECHAZADA')),
    confirmada_en    TIMESTAMP,
    tienda_id        VARCHAR(40),
    tienda_nombre    VARCHAR(150),
    torneo_id        BIGINT,
    torneo_nombre    VARCHAR(150),
    ronda            INTEGER      CHECK (ronda BETWEEN 1 AND 20),
    notas            VARCHAR(300),
    -- La ocultó el administrador (spam o datos falsos): deja de contar en las globales.
    oculta           BOOLEAN      NOT NULL DEFAULT false,
    creado_en        TIMESTAMP    NOT NULL DEFAULT now(),
    CHECK (rival_id IS NULL OR rival_id <> jugador_id),
    CHECK ((rival_id IS NULL) = (confirmacion = 'SIN_RIVAL')),
    CHECK (tipo = 'CASUAL' OR (tienda_id IS NOT NULL AND torneo_id IS NOT NULL AND ronda IS NOT NULL))
);
CREATE INDEX partidas_jugador_idx ON partidas (jugador_id, jugada_en DESC);
CREATE INDEX partidas_rival_idx ON partidas (rival_id, confirmacion) WHERE rival_id IS NOT NULL;
CREATE INDEX partidas_fecha_idx ON partidas (jugada_en);
CREATE INDEX partidas_torneo_idx ON partidas (tienda_id, torneo_id, ronda) WHERE tipo = 'TORNEO';

